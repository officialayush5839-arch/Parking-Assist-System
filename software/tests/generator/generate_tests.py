def main():
    ensure_dir(test_cases_dir)
    total_tests = 0
    total_folders = 0
    
    for mod in modules:
        folder_path = os.path.join(test_cases_dir, mod)
        ensure_dir(folder_path)
        total_folders += 1
        
        if mod == "03_initHardware":
            gen = generate_hardware_tests()
        elif mod == "04_initLCD":
            gen = generate_initLCD_tests()
        elif mod == "05_displayStartupMessage":
            gen = generate_startupMsg_tests()
        elif mod == "06_setup":
            gen = generate_setup_tests()
        elif mod == "07_loop":
            gen = generate_loop_tests()
        elif mod == "08_readDistance":
            gen = generate_readDistance_tests()
        elif mod == "09_updateLCD":
            gen = generate_updateLCD_tests()
        elif mod == "10_updateAlerts":
            gen = generate_updateAlerts_tests()
        elif mod == "11_beep":
            gen = generate_beep_tests()
        elif mod == "12_showSensorError":
            gen = generate_showError_tests()
        else:
            gen = generate_generic_tests(mod)
            
        gen.generate_excel(folder_path)
        gen.generate_markdowns(folder_path)
        
        total_tests += len(gen.test_cases)
        
        rel_path = os.path.join('software', 'Test Cases', mod)
        run_git_commands(rel_path, f"test: add {mod.split('_',1)[1]} test suite")
        
    print(f"Total tests generated: {total_tests}")
    print(f"Total folders created: {total_folders}")

if __name__ == "__main__":
    main()
